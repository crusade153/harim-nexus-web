using (
  (select private.is_nexus_admin())
  or exists (
    select 1 from public.members m
    where m.id = member_id and m.auth_id = (select auth.uid())
  )
)
with check (
  (select private.is_nexus_admin())
  or exists (
    select 1 from public.members m
    where m.id = member_id and m.auth_id = (select auth.uid())
  )
