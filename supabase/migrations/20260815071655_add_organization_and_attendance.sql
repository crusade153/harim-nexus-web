do $$
declare table_name text;
begin
  foreach table_name in array array[
    'org_units', 'member_role_profiles', 'mbo_objectives',
    'work_responsibilities', 'responsibility_assignments'
  ] loop
    execute format('drop policy if exists %I on public.%I', table_name || '_read_members', table_name);
    execute format(
      'create policy %I on public.%I for select to authenticated using ((select private.is_nexus_member()))',
      table_name || '_read_members', table_name
    );
    execute format('drop policy if exists %I on public.%I', table_name || '_admin_all', table_name);
    execute format(
      'create policy %I on public.%I for all to authenticated using ((select private.is_nexus_admin())) with check ((select private.is_nexus_admin()))',
      table_name || '_admin_all', table_name
    );
  end loop;
end $$;

drop policy if exists attendance_read_members on public.attendance_events;
create policy attendance_read_members on public.attendance_events
for select to authenticated
using ((select private.is_nexus_member()));

drop policy if exists attendance_insert_self_or_admin on public.attendance_events;
create policy attendance_insert_self_or_admin on public.attendance_events
for insert to authenticated
with check (
  (select private.is_nexus_admin())
  or exists (
    select 1 from public.members m
    where m.id = member_id and m.auth_id = (select auth.uid())
  )
);

