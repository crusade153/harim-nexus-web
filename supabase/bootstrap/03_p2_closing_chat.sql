-- ------------------------------------------------------------
-- 5. 월마감 실행 생성: 실행 1건 + 업무 N건을 한 트랜잭션으로
--    (업무 배정 알림·완료 시 AI 검토는 02 의 업무 트리거가 그대로 처리한다)
-- ------------------------------------------------------------
create or replace function harim_nexus.nexus_create_closing_run(
  p_workspace uuid, p_template bigint, p_period text, p_start date, p_actor bigint, p_tasks jsonb
) returns harim_nexus.closing_runs language plpgsql security invoker set search_path = '' as $$
declare r harim_nexus.closing_runs;
begin
  if jsonb_typeof(p_tasks) is distinct from 'array' or jsonb_array_length(p_tasks) = 0 then
    raise exception '월마감 항목이 없습니다.';
  end if;
  if not exists (select 1 from harim_nexus.closing_templates where id = p_template and workspace_id = p_workspace and active) then
    raise exception '사용 중인 월마감 템플릿이 아닙니다.';
  end if;
  begin
    insert into harim_nexus.closing_runs(workspace_id, template_id, period, start_date, created_by_member_id)
    values (p_workspace, p_template, p_period, p_start, p_actor) returning * into r;
  exception when unique_violation then
    raise exception '이미 시작된 월마감입니다: %', p_period;
  end;
  insert into harim_nexus.tasks(workspace_id, title, content, status, priority, assignee, assignee_member_id,
    due_date, start_date, source, source_ref, closing_run_id, closing_item_id, created_by_member_id)
  select p_workspace, left(t->>'title', 300), coalesce(t->>'content', ''), '대기', '보통', t->>'assignee',
    nullif(t->>'assignee_member_id', '')::bigint, t->>'due_date', p_start, 'closing', p_period, r.id,
    nullif(t->>'item_id', '')::bigint, p_actor
  from jsonb_array_elements(p_tasks) t;
  return r;
end $$;

-- ------------------------------------------------------------
-- 6. Chat 으로 보낼 알림을 집어 오기 (동시 실행돼도 한 번만 보냄)
-- ------------------------------------------------------------
create or replace function harim_nexus.nexus_claim_chat_notifications(p_workspace uuid, p_kinds text[], p_limit integer)
returns setof harim_nexus.notifications language plpgsql security invoker set search_path = '' as $$
declare since timestamptz;
begin
  select chat_enabled_at into since from harim_nexus.workspace_settings where workspace_id = p_workspace and chat_enabled;
  if since is null then return; end if;
  return query
  update harim_nexus.notifications n set chat_sent_at = now()
  where n.id in (
    select id from harim_nexus.notifications
    where workspace_id = p_workspace and chat_sent_at is null and kind = any(p_kinds)
      and created_at >= greatest(since, now() - interval '1 day')
    order by id limit least(greatest(p_limit, 1), 50)
    for update skip locked
  )
  returning n.*;
end $$;

-- 아침 브리핑 중복 방지: 오늘 처음 호출한 경우에만 true
create or replace function harim_nexus.nexus_claim_daily_brief(p_workspace uuid, p_date date)
returns boolean language plpgsql security invoker set search_path = '' as $$
declare claimed boolean;
begin
  update harim_nexus.workspace_settings set chat_last_brief_date = p_date
  where workspace_id = p_workspace and chat_enabled and chat_last_brief_date is distinct from p_date
  returning true into claimed;
  return coalesce(claimed, false);
end $$;

revoke all on function harim_nexus.nexus_create_closing_run(uuid, bigint, text, date, bigint, jsonb),
  harim_nexus.nexus_claim_chat_notifications(uuid, text[], integer),
  harim_nexus.nexus_claim_daily_brief(uuid, date) from public, anon, authenticated;
grant execute on function harim_nexus.nexus_create_closing_run(uuid, bigint, text, date, bigint, jsonb),
  harim_nexus.nexus_claim_chat_notifications(uuid, text[], integer),
  harim_nexus.nexus_claim_daily_brief(uuid, date) to service_role;

