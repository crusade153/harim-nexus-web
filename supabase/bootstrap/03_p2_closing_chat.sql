-- ------------------------------------------------------------
-- 2. 월마감 템플릿 · 항목 · 실행
-- ------------------------------------------------------------
create table if not exists harim_nexus.closing_templates (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null default '00000000-0000-4000-8000-000000000001' references harim_nexus.workspaces(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 100),
  description text not null default '' check (length(description) <= 2000),
  active boolean not null default true,
  auto_start boolean not null default false,
  created_by_member_id bigint references harim_nexus.members(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, name)
);

create table if not exists harim_nexus.closing_template_items (
  id bigint generated by default as identity primary key,
  template_id bigint not null references harim_nexus.closing_templates(id) on delete cascade,
  title text not null check (length(trim(title)) between 1 and 200),
  description text not null default '' check (length(description) <= 4000),
  offset_days integer not null default 0 check (offset_days between 0 and 30),
  default_assignee_member_id bigint references harim_nexus.members(id) on delete set null,
  reference_url text check (reference_url is null or reference_url ~ '^https?://'),
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists idx_closing_items_template on harim_nexus.closing_template_items(template_id, sort_order);
create index if not exists idx_closing_items_assignee on harim_nexus.closing_template_items(default_assignee_member_id);

create table if not exists harim_nexus.closing_runs (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null default '00000000-0000-4000-8000-000000000001' references harim_nexus.workspaces(id) on delete cascade,
  template_id bigint not null references harim_nexus.closing_templates(id) on delete restrict,
  period text not null check (period ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  start_date date not null,
  status text not null default 'open' check (status in ('open', 'closed')),
  created_by_member_id bigint references harim_nexus.members(id) on delete set null,
  created_at timestamptz not null default now(),
  closed_at timestamptz,
  unique (template_id, period)
);
create index if not exists idx_closing_runs_workspace on harim_nexus.closing_runs(workspace_id, period desc);
create index if not exists idx_closing_runs_creator on harim_nexus.closing_runs(created_by_member_id);

alter table harim_nexus.tasks add column if not exists closing_item_id bigint references harim_nexus.closing_template_items(id) on delete set null;
create index if not exists idx_tasks_closing_run on harim_nexus.tasks(closing_run_id) where closing_run_id is not null;
create index if not exists idx_tasks_closing_item on harim_nexus.tasks(closing_item_id) where closing_item_id is not null;
