create or replace function harim_nexus_private.current_nexus_member_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select m.id
  from harim_nexus.members m
  where m.auth_id = (select auth.uid())
    and m.approved is true
    and m.status <> 'pending'
  limit 1;
$$;

create or replace function harim_nexus_private.has_workspace_access(
  target_workspace uuid,
  allowed_roles text[] default null
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select (select auth.uid()) is not null and exists (
    select 1
    from harim_nexus.workspace_members wm
    join harim_nexus.members m on m.id = wm.member_id
    where wm.workspace_id = target_workspace
      and wm.active is true
      and m.auth_id = (select auth.uid())
      and m.approved is true
      and m.status <> 'pending'
      and (allowed_roles is null or wm.role = any(allowed_roles))
  );
$$;

revoke all on function harim_nexus_private.current_nexus_member_id() from public, anon;
revoke all on function harim_nexus_private.has_workspace_access(uuid, text[]) from public, anon;
