create or replace function harim_nexus_private.audit_nexus_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  row_json jsonb;
  old_json jsonb;
  action_name text;
  changed text[];
begin
  row_json := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  old_json := case when tg_op = 'UPDATE' then to_jsonb(old) else '{}'::jsonb end;

  if tg_op = 'INSERT' then
    action_name := 'create';
  elsif tg_op = 'DELETE' then
    action_name := 'delete';
  elsif (old_json->>'deleted_at') is null and (row_json->>'deleted_at') is not null then
    action_name := 'soft_delete';
  elsif (old_json->>'deleted_at') is not null and (row_json->>'deleted_at') is null then
    action_name := 'restore';
  else
    action_name := 'update';
  end if;

  if tg_op = 'UPDATE' then
    select coalesce(array_agg(key order by key), '{}') into changed
    from jsonb_each(row_json) n(key, value)
    where old_json->n.key is distinct from n.value
      and n.key not in ('updated_at');
  else
    changed := '{}';
  end if;

  insert into harim_nexus.audit_events (
    workspace_id, actor_id, actor_member_id, entity_type, entity_id, action, changed_fields
  ) values (
    (row_json->>'workspace_id')::uuid,
    (select auth.uid()),
    (select harim_nexus_private.current_nexus_member_id()),
    tg_table_name,
    row_json->>'id',
    action_name,
    changed
  );

  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

revoke all on function harim_nexus_private.audit_nexus_change() from public, anon, authenticated;

do $$
declare table_name text;
begin
  foreach table_name in array array['tasks', 'projects', 'posts', 'archives', 'comments', 'schedules', 'quick_links'] loop
    execute format('drop trigger if exists audit_nexus_change on harim_nexus.%I', table_name);
    execute format(
      'create trigger audit_nexus_change after insert or update or delete on harim_nexus.%I for each row execute function harim_nexus_private.audit_nexus_change()',
      table_name
    );
  end loop;
end $$;

